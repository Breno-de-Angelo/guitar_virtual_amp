use super::preset::Preset;

/// Factory preset JSON, embedded into the binary at compile time via
/// `include_str!` rather than read from disk at runtime. This is deliberate:
/// Android has no ordinary filesystem path to a bundled `assets/` directory
/// (it requires the NDK asset manager, a different API entirely), so baking
/// the content into the binary is the one loading strategy that works
/// identically on desktop and Android. Regenerate these files with
