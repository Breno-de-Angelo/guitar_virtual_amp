/// Parses every embedded factory preset. Malformed entries are skipped rather
/// than panicking -- this list is regenerated by a maintenance tool and
/// checked into the repo as plain files, so a bad entry should degrade
/// gracefully rather than crash the app at startup.
pub fn factory_presets() -> Vec<Preset> {
    let mut presets: Vec<Preset> = FACTORY_PRESET_JSON
        .iter()
        .filter_map(|json| serde_json::from_str(json).ok())
        .collect();
    presets.sort_by(|a, b| a.name.cmp(&b.name));
    presets
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn every_embedded_factory_preset_parses() {
        let presets = factory_presets();
        assert_eq!(
            presets.len(),
            FACTORY_PRESET_JSON.len(),
            "one or more factory preset JSON files failed to parse"
        );
    }

    #[test]
    fn factory_presets_have_unique_names() {
        let presets = factory_presets();
        let mut names: Vec<&str> = presets.iter().map(|p| p.name.as_str()).collect();
        let unique_count = {
            names.sort_unstable();
            names.dedup();
            names.len()
        };
        assert_eq!(unique_count, presets.len(), "factory preset names must be unique");
    }
}
